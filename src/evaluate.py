from src.model import (
    AnsweredQuestion,
    MinimalSource,
    RagDataset,
    StudentSearchResults,
)


class Evaluator:
    """Class used to build my own moulinette.
    Compare the search results with the answer key and
    compute the success rate (recall@k)."""

    def iou(self, a: MinimalSource, b: MinimalSource) -> float:
        """Measure the overlap between two passages of the same file
        (IoU = common part / total passage).
        args:
            - a -> passage from the answer key
            - b -> passage found by the search
        returns a value between 0.00 and 1.00 (0% and 100%)."""

        common: int = min(
            a.last_character_index, b.last_character_index
        ) - max(a.first_character_index, b.first_character_index)
        if common <= 0:
            return 0.00
        total: int = max(a.last_character_index, b.last_character_index) - min(
            a.first_character_index, b.first_character_index
        )
        iou: float = common / total
        return iou

    def is_match(self, a: MinimalSource, b: MinimalSource) -> bool:
        """Check that the file path is the same and that the IoU is
        at least 0.05.
            args:
                - a -> answer key
                - b -> generated result
        returns True if the paths are identical and IoU >= 0.05."""

        iou = self.iou(a, b)
        if a.file_path != b.file_path or iou < 0.05:
            return False
        return True

    def is_in_top_k(
        self, corriger: MinimalSource, results: list[MinimalSource], k: int
    ) -> bool:
        """Compare k results with the answer key and return True if one of
        them meets the conditions of is_match (same file_path and
        IoU >= 0.05).
            args:
                - corriger -> correct answer given by the subject
                - results -> list of results generated by the project
                - k -> number of results to check
        returns True if one element of the list matches the answer key.
        """
        for _, result in enumerate(results[:k]):
            if self.is_match(corriger, result):
                return True
        return False

    def recall_question(
        self,
        corriges: list[MinimalSource],
        results: list[MinimalSource],
        k: int,
    ) -> float:
        """Count the answer keys found and divide by the number of
        answer keys to get a score between 0 and 1 (1 = 100% valid).
            args:
                - corriges -> list of answers given by the subject
                - results -> list of results generated by the search
                - k -> number of results to check
        returns a score between 0 and 1."""

        if not corriges:
            return 0.00
        ok: int = 0
        for corrige in corriges:
            if self.is_in_top_k(corrige, results, k):
                ok += 1
        return ok / len(corriges)

    def recall_dataset(
        self, dataset: RagDataset, student: StudentSearchResults, k: int
    ) -> float:
        """Compute the final score, the recall@k over all the questions.
        This is what the moulinette displays.
            args:
                - dataset -> the answer key, RagDataset (all the questions
                with their sources)
                - student -> generated results, StudentSearchResults
                (all the questions with their retrieved_sources)
                - k -> number of results to look at
        returns a float between 0 and 1, the average score of all
        the questions
        """

        results_by_id: dict[str, list[MinimalSource]] = {}

        for search_result in student.search_results:
            results_by_id[search_result.question_id] = (
                search_result.retrieved_sources
            )
        total: float = 0.00
        for question in dataset.rag_questions:
            if not isinstance(question, AnsweredQuestion):
                continue
            results: list[MinimalSource] = results_by_id.get(
                question.question_id, []
            )
            total += self.recall_question(question.sources, results, k)
        return total / len(dataset.rag_questions)
