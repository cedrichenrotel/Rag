from pathlib import Path

import ollama

from src.bm25_index import Bm25Index
from src.corpus import ChunkCorpus
from src.model import Chunk, MinimalSource
from src.ollama_generator import OllamaGenerator
from src.path import PathFile
from src.qwen_generator import QwenGenerator


class RagCliUtils:
    def __init__(self) -> None:
        self._chunkcorpus: ChunkCorpus = ChunkCorpus()
        self._pathfile: PathFile = PathFile()

    def _check_token(self, name: str, value: int) -> bool:
        """Protect Ollama by checking the type and the value
        of the argument it will receive.

        Args:
            name (str): name of the checked variable
            value (int): value of max_new_tokens or max_context_tokens

        Returns:
            bool: True if ok.
        """

        is_valid: bool = True
        if not isinstance(value, int) or isinstance(value, bool) or value < 1:
            print(f"[ERROR] {name} must be an integer >= 1 (got {value})")
            is_valid = False
        return is_valid

    def _check_query(self, query: str) -> bool:
        """Check the type and the value of the query
        given by the user.

        Args:
            query (str): question asked

        Returns:
            bool: True if the type and the value are correct
        """

        is_valid: bool = True
        if not isinstance(query, str) or query.strip() == "":
            print("[ERROR] query must be a non-empty string.")
            is_valid = False
        return is_valid

    def _check_k(self, k: int) -> bool:
        """Check the type and the value of k
        given by the user.

        Args:
            k (int): number of results to return

        Returns:
            bool: True if the type and the value are correct
        """

        is_valid: bool = True
        if not isinstance(k, int) or isinstance(k, bool) or k < 1 or k > 10:
            print(f"[ERROR] k must be an integer between 1 and 10 (got {k})")
            is_valid = False
        return is_valid

    def _choose_generator(self) -> QwenGenerator:
        """Check that the Ollama server is running; if not, print a
        message warning that the generator will use Qwen
        (transformers) by default.

        Returns:
            QwenGenerator: OllamaGenerator | QwenGenerator (default)
        """

        try:
            list_ollama: ollama.ListResponse = ollama.list()
        except ConnectionError as e:
            print(f"[WARNING] Choose_generator: {e} -> activate Qwen default")
            return QwenGenerator()
        ollama_model: list[str | None] = [
            m.model for m in list_ollama.models
        ]

        if "qwen3:0.6b" not in ollama_model:
            print("[WARNING] Choose_generator: model qwen3:0.6b not found "
                  "on Ollama -> activate Qwen default")
            return QwenGenerator()
        return OllamaGenerator()

    def _read_source(self, source: MinimalSource) -> str:
        """Return a passage of text from its
        address (file + indexes).

        Args:
            source (MinimalSource): source found by BM25

        Returns:
            str: the passage between the 2 indexes
        """

        text: str = self._chunkcorpus.read_file(Path(source.file_path))
        return text[source.first_character_index:source.last_character_index]

    def _print_result(
        self, query: str, top_chunks: list[Chunk], answer: str | None = None
    ) -> None:
        """Display the results generated by search() or
        answer().

        Args:
            query (str): question to answer
            top_chunks (list[Chunk]): best chunks found by
            BM25.
            answer (str | None, optional): answer generated by the language
            model. Defaults to None.
        """

        print(f"\nQuery: {query}")
        print("\n        __ RANKINGS __  \n")
        for i, chunk in enumerate(top_chunks, start=1):
            print(f"Top {i}: {chunk.file_path}")
            print(
                f"    - First_character_index: {chunk.first_character_index}"
            )
            print(f"    - Last_character_index: {chunk.last_character_index}")
        if answer:
            print("\n     __ GENERATE ANSWER __\n")
            print(f"    - Answer: {answer}")
        print()

    def _to_sources(self, chunks: list[Chunk]) -> list[MinimalSource]:
        """Convert a list of chunks into a
        list[MinimalSource].

        Args:
            chunks (list[Chunk]): list of chunks returned by BM25

        Returns:
            list[MinimalSource]: a list of MinimalSource objects
        """

        sources: list[MinimalSource] = []
        for chunk in chunks:
            sources.append(
                MinimalSource(
                    file_path=chunk.file_path,
                    first_character_index=chunk.first_character_index,
                    last_character_index=chunk.last_character_index,
                )
            )
        return sources

    def _load_bm25(self, path: str) -> Bm25Index:
        """Load the chunks from the index file and build the BM25
        search tool.
        arg:
            - index_path -> path of the index file
        return: the Bm25Index, ready to receive questions"""

        list_chunk: list[Chunk] = self._pathfile.load(Path(path))
        bm25: Bm25Index = Bm25Index(list_chunk)
        return bm25
